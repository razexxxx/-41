// ---------- Окно рейтинга (п.1.1.4: таблица рейтинга, сортировка по очкам) ----------
static void ratingWindow(const Database& db) {
    std::cout << "\n---- \320\240\320\265\320\271\321\202\320\270\320\275\320\263 (\321\201\320\276\321\200\321\202\320\270\321\200\320\276\320\262\320\272\320\260 \320\277\320\276 \320\276\321\207\320\272\320\260\320\274) ----\n";
    auto recs = db.getRatingSorted();
    if (recs.empty()) {
        std::cout << "  \320\227\320\260\320\277\320\270\321\201\320\265\320\271 \320\277\320\276\320\272\320\260 \320\275\320\265\321\202 - \321\201\321\213\320\263\321\200\320\260\320\271\321\202\320\265 \320\277\320\260\321\200\321\202\320\270\321\216!\n";
        return;
    }
    std::cout << "  #  LOGIN            SCORE  FOOD  DATE          RESULT\n";
    int i = 1;
    for (const auto& r : recs) {
        char line[160];
        std::snprintf(line, sizeof(line), "%3d %-16s %6d %5d  %-13s ",
                      i++, r.playerLogin.c_str(), r.score, r.foodCount, r.gameDate.c_str());
        std::cout << line << r.result << "\n";
    }
}

