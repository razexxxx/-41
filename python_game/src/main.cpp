static std::string promptLine(const std::string& label) {
    std::cout << label;
    std::cout.flush();
    std::string s;
    if (!std::getline(std::cin, s)) return ""; // EOF -> пустая строка
    while (!s.empty() && s.back() == '\r') s.pop_back();
    return s;
}

